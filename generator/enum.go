const enumFileHeader = "// Code generated by gorm-plus enum generator. DO NOT EDIT."

type enumMember struct {
	Name  string // 常量的完整 Go 标识符。
	Value string // 数据库原始值，保留大小写及特殊字符。
	Label string // 字段备注明确提供的翻译；未提供时为空。
}

type enumDefinition struct {
	Name      string       // 按表名和字段名生成的枚举类型名称。
	LabelMap  string       // 枚举翻译 map 的私有名称。
	Comment   string       // 字段说明，移除值映射部分。
	Members   []enumMember // 按数据库定义顺序排列的枚举成员。
	HasLabels bool         // 是否包含至少一个明确翻译。
}

type enumTemplateData struct {
	Package string           // 实际 Model 输出包名。
	Enums   []enumDefinition // 当前数据表的全部枚举定义。
}

func enumIdentifier(value string) string { // 把数据库标识符转换成合法、可导出的 Go 名称。
	parts := strings.FieldsFunc(value, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	for i, part := range parts {
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		parts[i] = string(runes)
	}
	name := strings.Join(parts, "")
	if name == "" {
		return "Empty"
	}
	if unicode.IsDigit([]rune(name)[0]) {
		name = "Value" + name
	}
	return name
}

func enumTypeName(table, column string) string { // 每个表字段独立命名，数据库共享 ENUM 也不合并 Go 类型。
	if _, name, qualified := strings.Cut(table, "."); qualified {
		table = name
	}
	return enumIdentifier(table) + enumIdentifier(column) + "Enum"
}

func parseMySQLEnum(definition string) ([]string, error) { // 解析 MySQL ENUM 定义，支持引号、反斜杠及值中的逗号。
	s := strings.TrimSpace(definition)
	if !strings.HasPrefix(strings.ToLower(s), "enum(") {
		return nil, fmt.Errorf("不是完整的 ENUM 定义: %q", definition)
	}
	s = s[5:]
	var values []string
	for {
		s = strings.TrimSpace(s)
		if len(s) == 0 || s[0] != '\'' {
			return nil, fmt.Errorf("ENUM 值缺少单引号: %q", definition)
		}
		s = s[1:]
		var value strings.Builder
		closed := false
		for len(s) > 0 {
			ch := s[0]
			s = s[1:]
			if ch == '\'' {
				if len(s) > 0 && s[0] == '\'' {
					value.WriteByte('\'')
					s = s[1:]
					continue
				}
				closed = true
				break
			}
			if ch == '\\' {
				if len(s) == 0 {
					return nil, fmt.Errorf("ENUM 转义未结束: %q", definition)
				}
				ch, s = s[0], s[1:]
				switch ch {
				case '%', '_':
					value.WriteByte('\\')
				case '0':
					ch = 0
				case 'b':
					ch = '\b'
				case 'n':
					ch = '\n'
				case 'r':
					ch = '\r'
				case 't':
					ch = '\t'
				case 'Z':
					ch = 26
				}
			}
			value.WriteByte(ch)
		}
		if !closed {
			return nil, fmt.Errorf("ENUM 引号未结束: %q", definition)
		}
		values = append(values, value.String())
		s = strings.TrimSpace(s)
		if s == ")" {
			return values, nil
		}
		if len(s) == 0 || s[0] != ',' {
			return nil, fmt.Errorf("ENUM 分隔符错误: %q", definition)
		}
		s = s[1:]
	}
}

func loadNativeEnums(db *gorm.DB, table string, columns []ColumnInfo) error { // 从数据库目录读取真实枚举值，保持顺序及大小写。
	values := make(map[string][]string)
	switch db.Dialector.Name() {
	case "mysql":
		var rows []struct {
			Name       string // 字段名。
			Definition string // 完整 COLUMN_TYPE，不能使用被转小写后的类型。
		}
		schema, name := "", table
		if left, right, qualified := strings.Cut(table, "."); qualified {
			schema, name = left, right
		}
		query := "SELECT COLUMN_NAME AS name, COLUMN_TYPE AS definition FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = COALESCE(NULLIF(?, ''), DATABASE()) AND TABLE_NAME = ? AND DATA_TYPE = 'enum' ORDER BY ORDINAL_POSITION"
		if err := db.Raw(query, schema, name).Scan(&rows).Error; err != nil {
			return err
		}
		for _, row := range rows {
			members, err := parseMySQLEnum(row.Definition)
			if err != nil {
				return fmt.Errorf("字段 %s: %w", row.Name, err)
			}
			values[row.Name] = members
		}
	case "postgres":
		var rows []struct {
			Name  string // 绑定枚举类型的字段名。
			Value string // pg_enum 的原始标签。
		}
		stmt := &gorm.Statement{DB: db}
		if err := db.Raw(`SELECT a.attname AS name, e.enumlabel AS value
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_enum e ON e.enumtypid = a.atttypid
WHERE a.attrelid = to_regclass(?) AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum, e.enumsortorder`, stmt.Quote(table)).Scan(&rows).Error; err != nil {
			return err
		}
		for _, row := range rows {
			values[row.Name] = append(values[row.Name], row.Value)
		}
	default:
		return nil
	}
	for i := range columns {
		if members := values[columns[i].Name]; len(members) > 0 {
			columns[i].EnumValues = members
			columns[i].EnumTypeName = enumTypeName(table, columns[i].Name)
			columns[i].Type = "enum" // 不把枚举标签当 SQL 类型关键字解析。
		} else if db.Dialector.Name() == "mysql" && (columns[i].Type == "enum" || strings.HasPrefix(columns[i].Type, "enum(")) {
			return fmt.Errorf("字段 %s 无法读取原生 ENUM 值", columns[i].Name)
		}
	}
	return nil
}

func enumCommentLabels(comment string, values []string) (string, map[string]string) { // 只识别与数据库合法值对应的显式备注，绝不自动翻译或猜测含义。
	type marker struct {
		start int    // 映射开始位置。
		end   int    // 翻译文本开始位置。
		value string // 对应原始枚举值。
	}
	var markers []marker
	for _, value := range values {
		quoted := regexp.QuoteMeta(value)
		key := `(?:'` + quoted + `'|"` + quoted + `"|` + quoted + `)`
		if value == "" {
			key = `(?:''|"")`
		}
		pattern := `(?:^|[\s,，;；:：、(（])` + key + `\s*(?:=|:|：|、|是|[-.．])\s*`
		for _, pos := range regexp.MustCompile(pattern).FindAllStringIndex(comment, -1) {
			markers = append(markers, marker{pos[0], pos[1], value})
		}
	}
	sort.Slice(markers, func(i, j int) bool { return markers[i].start < markers[j].start })
	labels := make(map[string]string)
	description := comment
	for i, mark := range markers {
		end := len(comment)
		if i+1 < len(markers) {
			end = markers[i+1].start
		}
		if mark.end > end {
			continue
		}
		label := strings.TrimSpace(comment[mark.end:end])
		if p := strings.IndexAny(label, ",，;；\n\r"); p >= 0 {
			label = label[:p]
		}
		label = strings.Trim(label, " \t\r\n、。;；,，)）")
		if label != "" {
			labels[mark.value] = label
		}
	}
	if len(markers) > 0 {
		description = strings.TrimRight(comment[:markers[0].start], " \t\r\n:：;；,，、(（")
	}
	if description == "" {
		description = "枚举值"
	}
	return strings.Join(strings.Fields(description), " "), labels
}

func buildEnumDefinitions(table string, columns []ColumnInfo) ([]enumDefinition, error) { // 构建每张表的常量和可选翻译，并在写文件前拒绝命名冲突。
	var definitions []enumDefinition
	names := make(map[string]bool)
	for _, column := range columns {
		if len(column.EnumValues) == 0 {
			continue
		}
		name := enumTypeName(table, column.Name)
		if !token.IsIdentifier(name) || names[name] {
			return nil, fmt.Errorf("枚举类型名称冲突或非法: %s", name)
		}
		names[name] = true
		comment, labels := enumCommentLabels(column.Comment, column.EnumValues)
		definition := enumDefinition{Name: name, LabelMap: lowerFirst(name) + "Labels", Comment: comment}
		members := make(map[string]bool)
		for _, value := range column.EnumValues {
			constant := name + enumIdentifier(value)
			if !token.IsIdentifier(constant) || members[constant] {
				return nil, fmt.Errorf("%s 的枚举值 %q 生成重复或非法常量 %s", name, value, constant)
			}
			members[constant] = true
			label := strings.Join(strings.Fields(labels[value]), " ")
			definition.HasLabels = definition.HasLabels || label != ""
			definition.Members = append(definition.Members, enumMember{Name: constant, Value: value, Label: label})
		}
		definitions = append(definitions, definition)
	}
	return definitions, nil
}

func enumModelOptions(columns []ColumnInfo) []gen.ModelOpt { // 实体使用同包枚举，DAO 保留字符串查询能力。
	var opts []gen.ModelOpt
	for _, column := range columns {
		if column.EnumTypeName != "" {
			opts = append(opts, gen.FieldType(column.Name, column.EnumTypeName), gen.FieldGenType(column.Name, "String"))
		}
	}
	return opts
}

func writeEnumFile(path, templatePath, pkg string, definitions []enumDefinition) error { // 仅更新或清理本生成器拥有的枚举文件，保护用户文件。
	existing, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err == nil && !strings.HasPrefix(string(existing), enumFileHeader) {
		return fmt.Errorf("拒绝覆盖非生成枚举文件 %s", path)
	}
	if len(definitions) == 0 {
		if err == nil {
			return os.Remove(path)
		}
		return nil
	}
	content, err := renderTemplate(templatePath, enumTemplateData{Package: pkg, Enums: definitions})
	if err != nil {
		return err
	}
	formatted, err := format.Source([]byte(content))
	if err != nil {
		return fmt.Errorf("枚举代码格式错误: %w", err)
	}
	_, err = writeGeneratedFile(path, string(formatted), true)
	return err
}

func enumFileName(table string) string { // 文件名按表名生成，与实体生成文件分开。
	return strings.ToLower(strings.ReplaceAll(table, ".", "_")) + "_enum.gen.go"
}

func enumFilePath(cfg *Config, table string) string { // 枚举输出到实际实体目录，不另建枚举包。
	dir := cfg.ModelPkgPath
	if dir == "" {
		queryPath, _ := filepath.Abs(cfg.OutPath) // 与 gorm-gen 默认 Model 输出位置保持一致。
		dir = filepath.Join(filepath.Dir(queryPath), "model")
	}
	return filepath.Join(dir, enumFileName(table))
}

func quoteEnumValue(value string) string { // Go 与 Proto 的字符串字面量保留数据库原值。
	return strconv.Quote(value)
}

func nativeEnumOneof(values []string) string { // 对可安全表达的原生枚举生成 oneof；带单引号的值由 Valid 和数据库约束检查。
	params := make([]string, len(values))
	for i, value := range values {
		if strings.ContainsAny(value, "'\r\n\t") || strings.Contains(value, "0x2C") || strings.Contains(value, "0x7C") {
			return ""
		}
		value = strings.ReplaceAll(strings.ReplaceAll(value, ",", "0x2C"), "|", "0x7C")
		params[i] = "'" + value + "'"
	}
	return "oneof=" + strings.Join(params, " ")
}
